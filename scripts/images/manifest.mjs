for (const s of sections) {
  const rs = rows.filter((r) => r.a.section === s);
  md += `## ${s} (${rs.length})\n\n| File | Usage | Description | Dimensions | Format | Size | Alt text | Status |\n|---|---|---|---|---|---|---|---|\n`;
  for (const { a, checks, allOk } of rs) {
    const files = checks.map((c) => `\`${c.file}\``).join('<br>');
    const dims = checks.map((c) => c.dims).join('<br>');
    const fmt = [...new Set(checks.map((c) => path.extname(c.file).slice(1).toUpperCase()))].join(', ');
    const size = checks.map((c) => kb(c.bytes)).join('<br>');
    const alt = a.decorative ? '*(decorative, `alt=""`)*' : esc(a.alt);
    const seen = checks.some((c) => c.onPage) ? 'shown on a page' : 'decoded directly';
    const status = allOk ? `Verified: final illustration (${seen})` : '**Problem, see above**';
    md += `| ${files} | ${esc(a.usage)} | ${esc(a.description)} | ${dims} | ${fmt} | ${size} | ${alt} | ${status} |\n`;
  }
  md += '\n';
}

md += `## Source and licence by file type

| Files | Source | Licence |
|---|---|---|
| Heroes, specialties, doctors, facilities, products (WebP) | ${SOURCE} | ${LICENSE_RASTER} |
| Product box views, logo, favicon, app icons, share image | ${SOURCE} | ${LICENSE_TEXT} |
| Illustrations and category icons (SVG) | ${SOURCE} | ${LICENSE_RASTER} |
| Interface icons (inside components, not files) | [Lucide](https://lucide.dev) via \`lucide-react\` | ISC licence |

## Regenerating or replacing images

- \`npm run images\` re-renders all files from code. The output is deterministic.
- To swap in a real photograph, keep the same filename, or update the \`src\`, \`width\` and \`height\` in \`src/data/*.ts\`. Then provide the \`-sm.webp\` variant and run \`npm run build\`. The image check will fail if the dimensions do not match.
- Only use photographs you have the rights to: your own, commissioned, or licensed stock. Get signed consent from any staff member or patient shown.
`;

fs.writeFileSync(path.join(root, 'IMAGE_MANIFEST.md'), md);
console.log(`IMAGE_MANIFEST.md: ${verifiedAssets}/${totalAssets} assets verified, ${filesOk}/${filesTotal} files, ${problems.length} problem(s).`);
if (problems.length) process.exit(1);
